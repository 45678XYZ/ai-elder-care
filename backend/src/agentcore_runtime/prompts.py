def build_turn_prefix(local_time: str | None, lang: str | None) -> str:
    """組本輪對話的情境前綴。

    與長者的原話分開放進不同的 message：時間戳每輪都不同，混進長者發言會一起被寫進長期
    記憶，之後回顧對話就會看到一堆時間前綴。
    """
    parts = []
    if local_time:
        parts.append(f"目前台灣時間：{local_time}")
    if lang == "hak":
        parts.append("長者的偏好語言是客語，請以客語漢字回覆。")
    return "\n".join(parts)
