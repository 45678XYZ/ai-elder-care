/// 還沒有客語漢字的句子。
///
/// 列在這裡就知道畫面上哪幾處還會是華語，而不是等長輩用到才發現。
/// 缺譯不會壞畫面（[t] 原樣回華語），只是那一句沒有客語漢字。
const missingFromHakka = <String>[];

/// 把一句華語介面文字換成長輩選的書寫語言。
///
/// 沒選客語漢字、或這一句還沒翻，都原樣回 [zh]——**缺譯不會變成空字串或亂碼**，
/// 最差的情況只是那一句仍是華語。
String t(String zh) {
  if (!AppSession.instance.isHakkaText) return zh;
  return _hakka[zh] ?? zh;
}

/// 帶變數的版本：`t1('連結家人 {}', name)`。
///
/// 變數一律用 `{}` 而不是 Dart 的字串插值，因為要翻譯的是**模板**——插值會在
/// 查表之前就把值拼進去，查出來永遠是 miss。
String t1(String zh, Object a) => t(zh).replaceFirst('{}', '$a');

/// 兩個變數的版本，目前只有聊天狀態列的「（N 秒）」用得到。
String t2(String zh, Object a, Object b) =>
    t(zh).replaceFirst('{}', '$a').replaceFirst('{}', '$b');
